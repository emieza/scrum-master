def _oauth_app(prefix):
    client_id = env(f"{prefix}_OAUTH_CLIENT_ID").strip()
    client_secret = env(f"{prefix}_OAUTH_CLIENT_SECRET").strip()
    if client_id and client_secret:
        return {"client_id": client_id, "secret": client_secret}
    return None


